CREATE TABLE `el_user` (
    `id` INT NOT NULL AUTO_INCREMENT COMMENT '主键',
    `user_id` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '用户 ID',
    `account` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '账号，通常为手机号',
    `nick` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '昵称',
    `phone` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '手机号，不作为唯一标识',
    `avatar` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '头像',
    `status` INT NOT NULL DEFAULT 1 COMMENT '用户状态：1正常，2停用，3注销',
    `del_flag` BIGINT NOT NULL DEFAULT 1 COMMENT '逻辑删除标识：1正常，其他值删除',
    `source_type` INT NOT NULL DEFAULT 1 COMMENT '来源平台：1小象AI平台，2奔小象平台',
    `open_id` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '其他平台 OpenID',
    `password` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '用户密码哈希',
    `devicemodel` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '设备型号',
    `devicesysver` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '设备系统版本',
    `macid` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '设备 MAC ID',
    `resver` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '资源版本',
    `apkver` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '应用版本',
    `channel` VARCHAR(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '渠道',
    `signuptime` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '注册时间',
    `login_time` DATETIME DEFAULT NULL COMMENT '登录时间',
    `shell` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '产品外壳',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_user_id` (`user_id`),
    UNIQUE KEY `uq_account` (`account`, `del_flag`) USING BTREE,
    KEY `el_user_phone_IDX` (`phone`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='服务账户';
